//! The files that let a script read the run it is part of.
//!
//! The engine hands every script it launches a context file (its path is in
//! the `FORGE_CONTEXT` environment variable; see
//! `workflow_engine::RunContext::script_context`) holding the flow's
//! variables, the loop item, the action's args and earlier actions' outputs.
//! Reading and parsing that by hand in every script is the boilerplate this
//! module removes: it writes one small helper per language into the flow's
//! `.flow-scripts` folder, so a script just says
//!
//! ```js
//! import { variables, item } from "./forge.mjs";
//! ```
//!
//! The helpers are the same for every flow and every run. Values never go
//! into a file here: a `Foreach` runs its iterations at the same time, and
//! they would overwrite each other's copy. What *is* generated per flow is
//! the type declaration beside the helpers, which says what `variables` and
//! `actions` contain so an editor can complete and check them.

use std::path::Path;

use serde_json::Value;

/// First line of every generated file. Also how a file is recognized as
/// ours to rewrite: one without it is somebody's own and is left alone.
const GENERATED: &str = "Generated by the Forge Designer. Rewritten when the flow is saved or run.";

const HELPER_MJS: &str = r#"import { readFileSync } from "node:fs";

const file = process.env.FORGE_CONTEXT;
const context = file ? JSON.parse(readFileSync(file, "utf8")) : {};

/** The flow's variables, by name. */
export const variables = context.variables ?? {};
/** The current item of the enclosing Foreach, or null outside one. */
export const item = context.item ?? null;
/** This action's args, or the result of its argsExpression. */
export const args = context.args ?? null;
/** Outputs of the actions that have finished, by action id. */
export const actions = context.actions ?? {};

/** Print `value` as this action's outputs. Call it once, last. */
export function output(value) {
  console.log(JSON.stringify(value ?? {}));
}
"#;

const HELPER_CJS: &str = r#"const { readFileSync } = require("node:fs");

const file = process.env.FORGE_CONTEXT;
const context = file ? JSON.parse(readFileSync(file, "utf8")) : {};

module.exports = {
  /** The flow's variables, by name. */
  variables: context.variables ?? {},
  /** The current item of the enclosing Foreach, or null outside one. */
  item: context.item ?? null,
  /** This action's args, or the result of its argsExpression. */
  args: context.args ?? null,
  /** Outputs of the actions that have finished, by action id. */
  actions: context.actions ?? {},
  /** Print `value` as this action's outputs. Call it once, last. */
  output(value) {
    console.log(JSON.stringify(value ?? {}));
  },
};
"#;

const HELPER_PY: &str = r#"import json
import os

_file = os.environ.get("FORGE_CONTEXT")
_context = {}
if _file:
    with open(_file, encoding="utf-8") as _handle:
        _context = json.load(_handle)

# The flow's variables, by name.
variables = _context.get("variables") or {}
# The current item of the enclosing Foreach, or None outside one.
item = _context.get("item")
# This action's args, or the result of its argsExpression.
args = _context.get("args")
# Outputs of the actions that have finished, by action id.
actions = _context.get("actions") or {}


def output(value=None):
    """Print `value` as this action's outputs. Call it once, last."""
    print(json.dumps(value if value is not None else {}))
"#;

const HELPER_PS1: &str = r#"$ForgeContext = $null
if ($env:FORGE_CONTEXT) {
    $ForgeContext = Get-Content -Raw -LiteralPath $env:FORGE_CONTEXT | ConvertFrom-Json
}

# The flow's variables, by name: $Variables.MyName
$Variables = $ForgeContext.variables
# The current item of the enclosing Foreach, or $null outside one.
$Item = $ForgeContext.item
# This action's args, or the result of its argsExpression. ($Args is taken.)
$InputArgs = $ForgeContext.args
# Outputs of the actions that have finished, by action id.
$Actions = $ForgeContext.actions

# Print $Value as this action's outputs. Call it once, last.
function Write-ForgeOutput($Value) {
    if ($null -eq $Value) { $Value = @{} }
    $Value | ConvertTo-Json -Compress -Depth 32
}
"#;

/// The helper files, as `(file name, comment prefix, body)`.
const HELPERS: &[(&str, &str, &str)] = &[
    ("forge.mjs", "//", HELPER_MJS),
    ("forge.cjs", "//", HELPER_CJS),
    ("forge.py", "#", HELPER_PY),
    ("forge.ps1", "#", HELPER_PS1),
];

/// The type declaration files, one per JavaScript helper: TypeScript pairs
/// `forge.mjs` with `forge.d.mts` and `forge.cjs` with `forge.d.cts`.
const DECLARATIONS: &[&str] = &["forge.d.mts", "forge.d.cts"];

/// Writes `content` to `path` unless that is already what it holds, or the
/// file there isn't one of ours. Unchanged files aren't touched, so a save
/// doesn't show every helper as modified.
fn write_generated(path: &Path, content: &str) -> Result<(), String> {
    match std::fs::read_to_string(path) {
        Ok(existing) if existing == content => return Ok(()),
        Ok(existing) if !existing.contains(GENERATED) => return Ok(()),
        _ => {}
    }
    crate::script_companion::write_companion(path, content)
}

/// Puts the per-language helpers into `scripts_dir`.
pub fn ensure_helpers(scripts_dir: &Path) -> Result<(), String> {
    for (name, comment, body) in HELPERS {
        let content = format!("{comment} {GENERATED}\n{body}");
        write_generated(&scripts_dir.join(name), &content)?;
    }
    Ok(())
}

/// Writes the type declarations for the JavaScript helpers into
/// `scripts_dir`. `variables` and `actions` are `(name, TypeScript type)`.
pub fn write_declarations(
    scripts_dir: &Path,
    variables: &[(String, String)],
    actions: &[(String, String)],
) -> Result<(), String> {
    let content = declarations(variables, actions);
    for name in DECLARATIONS {
        write_generated(&scripts_dir.join(name), &content)?;
    }
    Ok(())
}

/// The declaration file's text. Members are sorted so the file only changes
/// when the flow does.
pub fn declarations(variables: &[(String, String)], actions: &[(String, String)]) -> String {
    let members = |entries: &[(String, String)], rest: &str| {
        let mut entries = entries.to_vec();
        entries.sort();
        entries.dedup_by(|a, b| a.0 == b.0);
        let mut text = String::from("{\n");
        for (name, ty) in entries {
            text.push_str(&format!("  {}: {ty};\n", Value::String(name)));
        }
        text.push_str(&format!("  [name: string]: {rest};\n}}"));
        text
    };
    format!(
        "// {GENERATED}\n\
         // Variable types come from the flow's Initialize Variable actions, and\n\
         // the shapes of values from the last run. They describe one run, so\n\
         // treat them as a guide to what is there, not a guarantee.\n\n\
         /** The flow's variables, by name. */\n\
         export declare const variables: {};\n\n\
         /** The current item of the enclosing Foreach, or null outside one. */\n\
         export declare const item: any;\n\n\
         /** This action's args, or the result of its argsExpression. */\n\
         export declare const args: any;\n\n\
         /** Outputs of the actions that have finished, by action id. */\n\
         export declare const actions: {};\n\n\
         /** Print `value` as this action's outputs. Call it once, last. */\n\
         export declare function output(value?: Record<string, unknown>): void;\n",
        members(variables, "unknown"),
        members(actions, "any"),
    )
}

/// How deep [`ts_type`] describes a sampled value before settling for
/// `unknown`.
const MAX_TYPE_DEPTH: usize = 5;

/// The TypeScript type of a sampled JSON `value`.
///
/// A list is typed from its first element, which is what the reference
/// chips sample too. An empty list or a `null` says nothing about what
/// belongs there, so both stay `unknown`.
pub fn ts_type(value: &Value) -> String {
    ts_type_at(value, 0)
}

fn ts_type_at(value: &Value, depth: usize) -> String {
    match value {
        Value::Null => "unknown".to_string(),
        Value::Bool(_) => "boolean".to_string(),
        Value::Number(_) => "number".to_string(),
        Value::String(_) => "string".to_string(),
        _ if depth >= MAX_TYPE_DEPTH => "unknown".to_string(),
        Value::Array(items) => match items.first() {
            Some(first) => {
                let element = ts_type_at(first, depth + 1);
                if element.contains(' ') {
                    format!("Array<{element}>")
                } else {
                    format!("{element}[]")
                }
            }
            None => "unknown[]".to_string(),
        },
        Value::Object(map) => {
            if map.is_empty() {
                return "Record<string, unknown>".to_string();
            }
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            let members: Vec<String> = keys
                .into_iter()
                .map(|key| {
                    format!(
                        "{}: {}",
                        Value::String(key.clone()),
                        ts_type_at(&map[key], depth + 1)
                    )
                })
                .collect();
            format!("{{ {} }}", members.join("; "))
        }
    }
}

/// The TypeScript type a variable has by declaration alone, before any run
/// has shown what it holds.
pub fn declared_ts_type(variable_type: &str) -> &'static str {
    match variable_type.trim().to_ascii_lowercase().as_str() {
        "string" => "string",
        "integer" => "number",
        "array" => "unknown[]",
        "object" => "Record<string, unknown>",
        _ => "unknown",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering};

    static NEXT_TEMP_ID: AtomicUsize = AtomicUsize::new(0);

    fn temp_dir() -> std::path::PathBuf {
        let id = NEXT_TEMP_ID.fetch_add(1, Ordering::Relaxed);
        let path = std::env::temp_dir().join(format!(
            "designer-script-helpers-{}-{id}",
            std::process::id()
        ));
        std::fs::create_dir_all(&path).unwrap();
        path
    }

    #[test]
    fn sampled_values_get_typescript_types() {
        assert_eq!(ts_type(&serde_json::json!("x")), "string");
        assert_eq!(ts_type(&serde_json::json!(3)), "number");
        assert_eq!(ts_type(&serde_json::json!(true)), "boolean");
        assert_eq!(ts_type(&Value::Null), "unknown");
        assert_eq!(ts_type(&serde_json::json!([1, 2])), "number[]");
        assert_eq!(ts_type(&serde_json::json!([])), "unknown[]");
        assert_eq!(ts_type(&serde_json::json!({})), "Record<string, unknown>");
        assert_eq!(
            ts_type(&serde_json::json!({"title": "T", "id": 7})),
            r#"{ "id": number; "title": string }"#
        );
        assert_eq!(
            ts_type(&serde_json::json!([{"id": 1}])),
            r#"Array<{ "id": number }>"#
        );
    }

    #[test]
    fn declared_types_cover_every_variable_type() {
        for name in workflow_engine::registry::VARIABLE_TYPES {
            assert_ne!(declared_ts_type(name), "unknown", "{name}");
        }
        assert_eq!(declared_ts_type("Integer"), "number");
    }

    #[test]
    fn declarations_name_each_variable_and_action() {
        let text = declarations(
            &[
                ("ids".to_string(), "number[]".to_string()),
                ("Count".to_string(), "number".to_string()),
            ],
            &[("http-1".to_string(), r#"{ "status": number }"#.to_string())],
        );
        assert!(text.contains(r#"  "Count": number;"#), "{text}");
        assert!(text.contains(r#"  "ids": number[];"#), "{text}");
        assert!(text.contains(r#"  "http-1": { "status": number };"#), "{text}");
        // Sorted, so the file is stable from one save to the next.
        assert!(text.find("\"Count\"").unwrap() < text.find("\"ids\"").unwrap());
        assert!(text.contains("export declare function output"));
    }

    /// Helpers are written once, refreshed when they differ, left alone when
    /// they don't, and never written over a file that isn't ours.
    #[test]
    fn helpers_are_written_and_only_rewritten_when_ours() {
        let dir = temp_dir();
        ensure_helpers(&dir).unwrap();
        for (name, _, body) in HELPERS {
            let written = std::fs::read_to_string(dir.join(name)).unwrap();
            assert!(written.contains(GENERATED), "{name}");
            assert!(written.ends_with(body), "{name}");
            assert!(written.contains("FORGE_CONTEXT"), "{name}");
        }

        // A stale generated helper is refreshed.
        let python = dir.join("forge.py");
        std::fs::write(&python, format!("# {GENERATED}\nold = True\n")).unwrap();
        // A file of the same name that somebody wrote is not.
        let own = dir.join("forge.ps1");
        std::fs::write(&own, "# mine\n").unwrap();

        ensure_helpers(&dir).unwrap();
        assert!(std::fs::read_to_string(&python).unwrap().ends_with(HELPER_PY));
        assert_eq!(std::fs::read_to_string(&own).unwrap(), "# mine\n");

        write_declarations(&dir, &[], &[]).unwrap();
        assert!(dir.join("forge.d.mts").is_file());
        assert!(dir.join("forge.d.cts").is_file());
    }
}
