/// A filled path made up of a series of closed quadratic Bezier segments.
#[derive(Clone, Debug)]
pub struct Path {
    pub bounds: Bounds<Pixels>,
    pub fill_rule: FillRule,
    monotone_curves: Vec<MonotoneCurve>,
    start: Point<Pixels>,
    current: Point<Pixels>,
}

/// A filled path, painted: its draw order, the paint row every tile
/// shares, and the device-space tiles renderers upload. [`Path::painted`]
/// is the only constructor, so a `PaintedPath` is always fully binned — a
/// self-contained primitive that can be inserted into a scene, cached, and
/// replayed with no further geometry work.
#[derive(Clone, Debug)]
pub struct PaintedPath {
    /// Draw order, assigned on scene insertion.
    pub order: DrawOrder,
    /// The per-path paint row shared by every tile of this path, uploaded
    /// once per path.
    pub paint: PathPaint,
    /// The device-space tiles of this path, one GPU instance each.
    pub tiles: Vec<PathTile>,
    /// The device-space curves, the binner's working form. Not uploaded:
    /// each tile's list carries its curves inline.
    pub curves: Vec<PathCurve>,
    /// Concatenated per-tile curve lists, indexed by
    /// [`PathTile::curve_start`].
    pub tile_curves: Vec<TileCurve>,
}

impl Path {
    /// Create a new path with the given starting point.
    pub fn new(start: Point<Pixels>) -> Self {
        Self {
            start,
            current: start,
            bounds: Bounds {
                origin: start,
                size: Default::default(),
            },
            fill_rule: FillRule::NonZero,
            monotone_curves: Vec::new(),
        }
    }

    /// Paint this path: scale the geometry into device pixels, clip it to
    /// `content_mask`, and bin it into tiles, once. The built path is left
    /// untouched and can be painted again (at any scale).
    pub(crate) fn painted(
        &self,
        scale_factor: f32,
        content_mask: ContentMask<Pixels>,
        color: Background,
    ) -> PaintedPath {
        let mut painted = PaintedPath {
            order: DrawOrder::default(),
            paint: PathPaint {
                bounds: self.bounds.scale(scale_factor),
                content_mask: content_mask.scale(scale_factor),
                color,
                even_odd: matches!(self.fill_rule, FillRule::EvenOdd).into(),
            },
            tiles: Vec::new(),
            curves: Vec::new(),
            tile_curves: Vec::new(),
        };
        // Fill semantics treat every contour as closed; an open final
        // contour is closed virtually so painting need not mutate the
        // built path. Only segment-pushing calls move `current` away from
        // `start`, so the inequality also proves the open contour is
        // non-empty.
        let closing_curve = (self.current != self.start)
            .then(|| {
                MonotoneCurve::from_line(
                    point(self.current.x.0, self.current.y.0),
                    point(self.start.x.0, self.start.y.0),
                )
            })
            .flatten();
        painted.bin(&self.monotone_curves, closing_curve, scale_factor);
        painted
    }

    /// Close the current contour and start a new one at the given point.
    pub fn move_to(&mut self, to: Point<Pixels>) {
        self.close();
        self.start = to;
        self.current = to;
    }

    /// Draw a straight line from the current point to the given point.
    pub fn line_to(&mut self, to: Point<Pixels>) {
        if to != self.current {
            let midpoint = point(
                px(0.5 * (self.current.x.0 + to.x.0)),
                px(0.5 * (self.current.y.0 + to.y.0)),
            );
            self.push_segment(self.current, midpoint, to);
            self.current = to;
        }
    }

    /// Draw a curve from the current point to the given point, using the given control point.
    pub fn curve_to(&mut self, to: Point<Pixels>, ctrl: Point<Pixels>) {
        if to == self.current && ctrl == self.current {
            return;
        }
        self.push_segment(self.current, ctrl, to);
        self.current = to;
    }

    /// Close the current contour with a straight line back to its start.
    pub fn close(&mut self) {
        if self.current != self.start {
            let start = self.start;
            self.line_to(start);
        }
        self.current = self.start;
    }

    fn push_segment(&mut self, p0: Point<Pixels>, ctrl: Point<Pixels>, p1: Point<Pixels>) {
        for position in [p0, ctrl, p1] {
            self.bounds = self.bounds.union(&Bounds {
                origin: position,
                size: Default::default(),
            });
        }

        decompose_quadratic(
            &mut self.monotone_curves,
            point(p0.x.0, p0.y.0),
            point(ctrl.x.0, ctrl.y.0),
            point(p1.x.0, p1.y.0),
        );
    }
}

impl From<PaintedPath> for Primitive {
    fn from(path: PaintedPath) -> Self {
        Primitive::Path(path)
    }
}
