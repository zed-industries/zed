pub trait AgentConnection {
    fn agent_id(&self) -> AgentId;

    fn telemetry_id(&self) -> SharedString;

    fn agent_version(&self) -> Option<SharedString> {
        None
    }

    /// Initiate shutdown of connection-owned resources when their shared UI owner ends.
    /// This is independent of session close and may leave retained models alive.
    /// It does not wait for process exit or a complete protocol drain.
    fn shutdown(&self) {}

    fn new_session(
        self: Rc<Self>,
        project: Entity<Project>,
        _work_dirs: PathList,
        cx: &mut App,
    ) -> Task<Result<Entity<AcpThread>>>;

    /// Whether this agent supports loading existing sessions.
    fn supports_load_session(&self) -> bool {
        false
    }

    /// Load an existing session by ID.
    fn load_session(
        self: Rc<Self>,
        _session_id: acp_v2::SessionId,
        _project: Entity<Project>,
        _work_dirs: PathList,
        _title: Option<SharedString>,
        _cx: &mut App,
    ) -> Task<Result<Entity<AcpThread>>> {
        Task::ready(Err(anyhow::Error::msg("Loading sessions is not supported")))
    }

    /// Whether this agent supports explicitly closing existing sessions.
    fn supports_close_session(&self) -> bool {
        false
    }

    /// Whether subagents follow the ACP subagents RFD on this connection: they are discovered
    /// only through their parent's announcements, and must never be loaded or resumed.
    fn announces_subagents(&self) -> bool {
        false
    }

    /// Whether conversation teardown should invoke `close_session`.
    /// The default preserves existing UI cleanup; backend-owned release hooks are separate.
    /// Autonomous backends can opt out without disabling explicit close support.
    fn should_close_sessions_on_release(&self) -> bool {
        self.supports_close_session()
    }

    /// Close an existing session and free its resources. This may cancel remote work;
    /// automatic cleanup must also respect `should_close_sessions_on_release`.
    fn close_session(
        self: Rc<Self>,
        _session_id: &acp_v2::SessionId,
        _cx: &mut App,
    ) -> Task<Result<()>> {
        Task::ready(Err(anyhow::Error::msg("Closing sessions is not supported")))
    }

    /// Whether this agent supports resuming existing sessions without loading history.
    fn supports_resume_session(&self) -> bool {
        false
    }

    /// Resume an existing session by ID without replaying previous messages.
    fn resume_session(
        self: Rc<Self>,
        _session_id: acp_v2::SessionId,
        _project: Entity<Project>,
        _work_dirs: PathList,
        _title: Option<SharedString>,
        _cx: &mut App,
    ) -> Task<Result<Entity<AcpThread>>> {
        Task::ready(Err(anyhow::Error::msg(
            "Resuming sessions is not supported",
        )))
    }

    /// Whether this agent supports showing session history.
    fn supports_session_history(&self) -> bool {
        self.supports_load_session() || self.supports_resume_session()
    }

    /// Whether this agent supports additional session directories.
    fn supports_session_additional_directories(&self) -> bool {
        false
    }

    fn auth_methods(&self) -> &[acp_v2::AuthMethod];

    fn terminal_auth_task(
        &self,
        _method: &acp_v2::AuthMethodId,
        _cx: &App,
    ) -> Option<Task<Result<SpawnInTerminal>>> {
        None
    }

    fn authenticate(&self, method: acp_v2::AuthMethodId, cx: &mut App) -> Task<Result<()>>;

    fn supports_logout(&self) -> bool {
        false
    }

    fn logout(&self, _cx: &mut App) -> Task<Result<()>> {
        Task::ready(Err(anyhow::Error::msg("Logout is not supported")))
    }

    /// Returns a capability for agents that accept client-generated user message IDs.
    fn client_user_message_ids(
        &self,
        _cx: &App,
    ) -> Option<Rc<dyn AgentSessionClientUserMessageIds>> {
        None
    }

    /// Selected during thread construction, before backend registration may be complete.
    /// Validate the submitting owner when publishing, not when selecting this capability.
    fn receipt_submissions(
        &self,
        _session_id: &acp_v2::SessionId,
        _cx: &App,
    ) -> Option<Rc<dyn ReceiptSessionSubmissions>> {
        None
    }

    /// Preflight without starting transport work so rejection cannot interrupt an
    /// existing turn. Adapters must also validate when called directly.
    fn validate_prompt_content(&self, _content: &[acp_v2::ContentBlock]) -> Result<()> {
        Ok(())
    }

    /// Receipt transports acknowledge acceptance through `receipt_submissions`
    /// instead of implementing this completion-based path.
    fn prompt(
        &self,
        _params: acp_v2::PromptRequest,
        _cx: &mut App,
    ) -> Task<Result<acp_v1::PromptResponse>> {
        Task::ready(Err(anyhow::anyhow!(
            "This agent does not support completion-based prompts"
        )))
    }

    fn retry(
        &self,
        _session_id: &acp_v2::SessionId,
        _cx: &App,
    ) -> Option<Rc<dyn AgentSessionRetry>> {
        None
    }

    /// Requests cancellation; success does not establish that execution stopped.
    fn cancel(&self, session_id: &acp_v2::SessionId, cx: &mut App) -> Result<()>;

    /// Request-scoped elicitations are connection-level because they can arrive before a session
    /// thread exists. Session-scoped elicitations stay in the thread timeline, but use
    /// `ElicitationStore` for shared processing.
    fn request_elicitations(&self) -> Option<Entity<ElicitationStore>> {
        None
    }

    fn truncate(
        &self,
        _session_id: &acp_v2::SessionId,
        _cx: &App,
    ) -> Option<Rc<dyn AgentSessionTruncate>> {
        None
    }

    fn set_title(
        &self,
        _session_id: &acp_v2::SessionId,
        _cx: &App,
    ) -> Option<Rc<dyn AgentSessionSetTitle>> {
        None
    }

    /// Returns this agent as an [Rc<dyn ModelSelector>] if the model selection capability is supported.
    ///
    /// If the agent does not support model selection, returns [None].
    /// This allows sharing the selector in UI components.
    fn model_selector(
        &self,
        _session_id: &acp_v2::SessionId,
    ) -> Option<Rc<dyn AgentModelSelector>> {
        None
    }

    fn telemetry(&self) -> Option<Rc<dyn AgentTelemetry>> {
        None
    }

    fn session_modes(
        &self,
        _session_id: &acp_v2::SessionId,
        _cx: &App,
    ) -> Option<Rc<dyn AgentSessionModes>> {
        None
    }

    fn session_config_options(
        &self,
        _session_id: &acp_v2::SessionId,
        _cx: &App,
    ) -> Option<Rc<dyn AgentSessionConfigOptions>> {
        None
    }

    fn session_list(&self, _cx: &mut App) -> Option<Rc<dyn AgentSessionList>> {
        None
    }

    fn into_any(self: Rc<Self>) -> Rc<dyn Any>;
}

